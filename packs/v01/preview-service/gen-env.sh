#!/usr/bin/env bash
# Generate packs/v01/.env.preview (read by preview-service) and packs/v01/.env.preview.core (read
# by the Cobble api/worker). Both are mode 600 and never committed. Idempotent: an existing
# service token is kept. Needs packs/v01/.env.pack (written by hooks/register-core.sh).
set -euo pipefail
PACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PACK_ENV="${COBBLE_PACK_CORE_ENV:-$PACK_DIR/.env.pack}"
OUT="${COBBLE_PREVIEW_ENV:-$PACK_DIR/.env.preview}"
OUT_CORE="${COBBLE_PREVIEW_CORE_ENV:-$PACK_DIR/.env.preview.core}"

get() { sed -n "s/^$2=//p" "$1" 2>/dev/null | tail -n 1; }

[ -f "$PACK_ENV" ] || { echo "missing $PACK_ENV: run the pack install first" >&2; exit 1; }
token="$(get "$OUT" COBBLE_PREVIEW_SERVICE_TOKEN)"
[ -n "$token" ] || token="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"

umask 077
{
  echo "# Generated by preview-service/gen-env.sh. Do not commit."
  echo "COBBLE_PREVIEW_SERVICE_TOKEN=$token"
  # Internal Forgejo address for git (clone); credentials stay in this service.
  echo "COBBLE_PACK_FORGEJO_URL=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_URL)"
  echo "COBBLE_PACK_FORGEJO_TOKEN=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_TOKEN)"
  echo "COBBLE_PACK_FORGEJO_OWNER=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_OWNER)"
  [ -z "${COBBLE_PREVIEW_GIT_REWRITE:-}" ] || echo "COBBLE_PREVIEW_GIT_REWRITE=$COBBLE_PREVIEW_GIT_REWRITE"
} > "$OUT"
{
  echo "# Generated by preview-service/gen-env.sh. Do not commit."
  echo "COBBLE_PREVIEW_SERVICE_URL=http://preview-service:8091"
  echo "COBBLE_PREVIEW_SERVICE_TOKEN=$token"
} > "$OUT_CORE"
chmod 600 "$OUT" "$OUT_CORE"
echo "wrote $OUT and $OUT_CORE"
