#!/usr/bin/env bash
# Generate packs/v01/.env.agents (read by agent-service) and packs/v01/.env.agents.core (read by
# the Cobble api/worker). Both are mode 600 and never committed. Idempotent: an existing
# service token is kept. Needs packs/v01/.env.pack (written by hooks/register-core.sh).
set -euo pipefail
PACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PACK_ENV="${COBBLE_PACK_CORE_ENV:-$PACK_DIR/.env.pack}"
OUT="${COBBLE_AGENT_ENV:-$PACK_DIR/.env.agents}"
OUT_CORE="${COBBLE_AGENT_CORE_ENV:-$PACK_DIR/.env.agents.core}"
API_URL="${COBBLE_INTERNAL_API_URL:-http://api:8000/internal/llm/v1}"

get() { sed -n "s/^$2=//p" "$1" 2>/dev/null | tail -n 1; }

[ -f "$PACK_ENV" ] || { echo "missing $PACK_ENV: run the pack install first" >&2; exit 1; }
token="$(get "$OUT" COBBLE_AGENT_SERVICE_TOKEN)"
[ -n "$token" ] || token="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"

umask 077
{
  echo "# Generated by agent-service/gen-env.sh. Do not commit."
  echo "COBBLE_AGENT_SERVICE_TOKEN=$token"
  echo "COBBLE_INTERNAL_API_URL=$API_URL"
  # Internal Forgejo address for git (clone/push); credentials stay in this service.
  echo "COBBLE_PACK_FORGEJO_URL=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_URL)"
  echo "COBBLE_PACK_FORGEJO_TOKEN=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_TOKEN)"
  echo "COBBLE_PACK_FORGEJO_OWNER=$(get "$PACK_ENV" COBBLE_PACK_FORGEJO_OWNER)"
  # Public clone URLs reported by Forgejo -> internal URL (set by the operator if needed):
  [ -z "${COBBLE_AGENT_GIT_REWRITE:-}" ] || echo "COBBLE_AGENT_GIT_REWRITE=$COBBLE_AGENT_GIT_REWRITE"
} > "$OUT"
{
  echo "# Generated by agent-service/gen-env.sh. Do not commit."
  echo "COBBLE_AGENT_SERVICE_URL=http://agent-service:8090"
  echo "COBBLE_AGENT_SERVICE_TOKEN=$token"
} > "$OUT_CORE"
chmod 600 "$OUT" "$OUT_CORE"
echo "wrote $OUT and $OUT_CORE"
