#!/usr/bin/env bash
# Write the endpoints and tokens the core reads (COBBLE_PACK_* variables) to .env.pack
# (mode 600, outside git). Load it in the api and worker services: `env_file: [.env.pack]`.
#
# Usage: hooks/register-core.sh [--out FILE] [--forgejo-url URL] [--woodpecker-url URL]
#   The default URLs are the in-network ones (core and pack share the cobble_core network).
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

out="$CORE_ENV_FILE"
forgejo_url="http://forgejo:3000"
woodpecker_url="http://woodpecker-server:8000/ci"
while [ $# -gt 0 ]; do
  case "$1" in
    --out) out="$2"; shift 2 ;;
    --forgejo-url) forgejo_url="$2"; shift 2 ;;
    --woodpecker-url) woodpecker_url="$2"; shift 2 ;;
    *) die "usage: register-core.sh [--out FILE] [--forgejo-url URL] [--woodpecker-url URL]" ;;
  esac
done

ftoken="$(env_get "$ENV_FILE" PACK_FORGEJO_TOKEN)"
wtoken="$(env_get "$ENV_FILE" PACK_WOODPECKER_TOKEN)"
[ -n "$ftoken" ] && [ -n "$wtoken" ] || die "the pack is not installed yet (run hooks/install.sh)"

( umask 077
  tmp="$(mktemp "$out.XXXXXX")"
  {
    echo "# Generated by packs/v01/hooks/register-core.sh. Secret: never commit."
    echo "COBBLE_PACK_FORGEJO_URL=$forgejo_url"
    echo "COBBLE_PACK_FORGEJO_TOKEN=$ftoken"
    echo "COBBLE_PACK_FORGEJO_OWNER=$(env_get "$ENV_FILE" PACK_SERVICE_USER)"
    echo "COBBLE_PACK_WOODPECKER_URL=$woodpecker_url"
    echo "COBBLE_PACK_WOODPECKER_TOKEN=$wtoken"
  } >"$tmp"
  mv "$tmp" "$out" )
chmod 600 "$out"
log "wrote $out"
