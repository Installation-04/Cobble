#!/usr/bin/env python3
"""Generate `core/compose.release.yml`: the compose override of a published release.

    scripts/make_release_compose.py --compose core/compose.yml --owner Installation-04 \
        --version v0.3.0 --digest api=sha256:<hex> --digest worker=sha256:<hex> ... \
        --output core/compose.release.yml

Every service of `compose.yml` that has a `build:` section gets
`image: ghcr.io/<owner>/cobble-<service>:<version>@sha256:<digest>` (and `pull_policy: always`, so
Compose pulls that exact image instead of building the service). The profile of a service does not
matter: a service of an inactive profile (the module-manager) is still pinned. The output is
deterministic (services sorted by name, no timestamp). Exit code 1 when a built service has no
digest, when a digest is given for a service that does not build, or when an argument is invalid.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z][0-9A-Za-z.-]*)?$")
OWNER = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]*$")
SERVICE = re.compile(r"^[a-z0-9][a-z0-9-]*$")

HEADER = """\
# Generated by scripts/make_release_compose.py for the release {version}. Do not edit.
# Use it on top of core/compose.yml: it replaces the local build of every built service by the
# image CI published (pinned by digest).
"""


class ReleaseComposeError(ValueError):
    """The override cannot be generated; the message is meant for the maintainer."""


def built_services(compose: Any) -> list[str]:
    """The services that have a `build:` section, sorted by name."""
    services = compose.get("services") if isinstance(compose, dict) else None
    if not isinstance(services, dict):
        raise ReleaseComposeError("compose file has no services")
    return sorted(
        name for name, spec in services.items() if isinstance(spec, dict) and "build" in spec
    )


def parse_digests(items: list[str]) -> dict[str, str]:
    """`service=sha256:<hex>` items to a mapping."""
    digests: dict[str, str] = {}
    for item in items:
        service, sep, digest = item.partition("=")
        if not sep or not SERVICE.match(service) or not DIGEST.match(digest):
            raise ReleaseComposeError(f"not a service=sha256:<64 hex> pair: {item!r}")
        if service in digests and digests[service] != digest:
            raise ReleaseComposeError(f"two different digests for {service}")
        digests[service] = digest
    return digests


def generate(compose: Any, owner: str, version: str, digests: dict[str, str]) -> str:
    version = version.removeprefix("v")
    if not VERSION.match(version):
        raise ReleaseComposeError(f"not a version (expected X.Y.Z[-suffix]): {version!r}")
    if not OWNER.match(owner):
        raise ReleaseComposeError(f"not a registry owner: {owner!r}")
    owner = owner.lower()  # registry names are lower case
    services = built_services(compose)
    missing = [name for name in services if name not in digests]
    if missing:
        raise ReleaseComposeError("no digest for built service(s): " + ", ".join(missing))
    extra = sorted(set(digests) - set(services))
    if extra:
        raise ReleaseComposeError(
            "digest given for service(s) that do not build: " + ", ".join(extra)
        )
    lines = [HEADER.format(version=version).rstrip("\n"), "services:"]
    for name in services:
        lines += [
            f"  {name}:",
            f"    image: ghcr.io/{owner}/cobble-{name}:{version}@{digests[name]}",
            "    pull_policy: always",
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate core/compose.release.yml.")
    parser.add_argument("--compose", type=Path, required=True)
    parser.add_argument("--owner", required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--digest", action="append", default=[], metavar="SERVICE=sha256:HEX")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        compose = yaml.safe_load(args.compose.read_text("utf-8"))
        text = generate(compose, args.owner, args.version, parse_digests(args.digest))
    except (ReleaseComposeError, yaml.YAMLError, OSError) as error:
        print(f"make_release_compose: {error}", file=sys.stderr)
        return 1
    args.output.write_text(text, "utf-8")
    print(f"wrote {args.output} ({text.count('image:')} images)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
